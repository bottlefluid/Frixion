// Sumi joins Tester's server by its invite, writes a message, starts a thread on it and writes in the thread.
const { check, until, sql, doc } = T;
check('Sumi logs in', await T.login('Sumi'));
openModal('join-server-modal');
$('join-server-code').value = 'ptest';
await $('confirm-join-server').onclick();
const srv = await until(() => (window.__myServers || []).find(s => s.inviteCode === 'ptest'));
check('join by invite', !!srv && srv.members.includes('Sumi'), $('join-server-error').textContent);
if (!srv) return T.report();
const card = await until(async () => { const c = await doc('serverCards/' + srv.id); return c && c.memberCount === 2 ? c : null; });
check('the invite card counts 2 members', !!card);
selectServer(srv);
await until(() => currentServerId === srv.id && currentChannelId);
const cid = currentChannelId;
$('composer-input').value = 'thread starter';
await sendMessage();
const m = await until(() => lastRawMessages.find(x => x.text === 'thread starter'));
check('a message in the new server', !!m);
if (!m) return T.report();
openCreateThread(m.id);
$('thread-name').value = 'test thread';
await createThreadFromModal();
const th = await until(() => currentThreadId);
check('a thread on it', !!th, $('thread-error').textContent);
if (!th) return T.report();
$('composer-input').value = 'inside the thread';
await sendMessage();
check('a message in the thread', !!(await until(async () => (await sql("select 1 from public.thread_messages where server_id = $1 and thread_id = $2 and data->>'text' = 'inside the thread'", [srv.id, th])).length)));
check('the starter message points at the thread', !!(await until(async () => { const d = await doc(`servers/${srv.id}/channels/${cid}/messages/${m.id}`); return d && d.thread && d.thread.id === th; })));
goToThreadParent();
return T.report();
